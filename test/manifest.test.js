'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const read = p => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));

const app = read('app.json');
const composeApp = read('.homeycompose/app.json');
const signal = read('.homeycompose/signals/433/bear.json');
const driverCompose = read('drivers/blind/driver.compose.json');
const protocol = require('../drivers/blind/bear-protocol');
const { identifyFrame } = protocol;

// app.json is generated by `homey app build` and committed. These catch it
// drifting from the .homeycompose sources it was generated from.
test('app.json is in step with .homeycompose', async (t) => {
    await t.test('app metadata', () => {
        assert.equal(app.id, composeApp.id);
        assert.equal(app.version, composeApp.version);
        assert.deepEqual(app.permissions, ['homey:wireless:433']);
    });

    await t.test('signal', () => {
        assert.deepEqual(app.signals[433][protocol.SIGNAL_ID], signal);
    });

    await t.test('driver', () => {
        const driver = app.drivers.find(d => d.id === 'blind');
        assert.ok(driver, 'blind driver is present');
        assert.deepEqual(driver.capabilities, driverCompose.capabilities);
        assert.equal(driver.class, driverCompose.class);
    });
});

test('the version in package.json matches the app manifest', () => {
    assert.equal(read('package.json').version, app.version);
});

test('the driver is a blind that Homey will route received frames to', () => {
    // windowcoverings_state is Homey's native up/idle/down ternary. Homey
    // generates its flow cards, which is why this app defines none of its own.
    assert.deepEqual(driverCompose.capabilities, ['windowcoverings_state']);
    assert.deepEqual(driverCompose.connectivity, ['rf433']);

    // Without satelliteMode Homey routes no received frame to the driver at all,
    // while enableRX() still resolves successfully. See RF_PROTOCOL.md.
    assert.equal(driverCompose.rf433.satelliteMode, true);
});

test('the signal accepts the frame length the protocol builds', () => {
    // The window is deliberately wider than the frame while RX is being brought
    // up, so a frame that loses a symbol surfaces in the log instead of being
    // dropped by Homey before the payload event. identifyFrame still requires
    // exactly FRAME_LENGTH, so nothing shorter can reach a device.
    assert.ok(signal.minimalLength <= protocol.FRAME_LENGTH, 'minimalLength admits the frame');
    assert.ok(signal.maximalLength >= protocol.FRAME_LENGTH, 'maximalLength admits the frame');
    assert.equal(identifyFrame(Array(protocol.FRAME_LENGTH - 1).fill(0)), null);
    assert.equal(identifyFrame(Array(protocol.FRAME_LENGTH + 1).fill(0)), null);
});
